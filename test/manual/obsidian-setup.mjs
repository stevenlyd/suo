import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { initVault, adoptVaultNote, readVaultDraft, approveVaultDraft, loadSnapshot, saveSnapshot, stageProposal, approveProposal, generateArtifacts } from '../../dist/index.js';
const work=process.env.SUO_OBSIDIAN_TEST_DIR;
if (!work) throw new Error('Set SUO_OBSIDIAN_TEST_DIR to a new isolated test directory');
const root=work+'/vault';
await initVault(root,'Test Suo with the real Obsidian desktop application','Suo Desktop Test');
await mkdir(root+'/Projects',{recursive:true});
await writeFile(root+'/Projects/Portal.md','# Portal research\n\nA personal note, preserved by Suo.\n');
