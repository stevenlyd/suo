import { mkdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import type { Closure, Decision, Handoff, NextProductAction, ProductFrontierSnapshot, ProductModule } from './model.js'
import { moduleTopologicalOrder, nextAction } from './core.js'
import { workspaceDir } from './store.js'

const generatedBanner = '<!-- GENERATED by Product Frontier. DO NOT EDIT. -->'
const lineList = (values: string[]) => values.length ? values.map(value => `- ${value}`).join('\n') : '- None'

export function renderNext(action: NextProductAction): string {
  const unlocks = 'whatItUnlocks' in action && action.whatItUnlocks.length ? `

## What it unlocks
${lineList(action.whatItUnlocks)}` : ''
  const recommendation = 'recommendation' in action && action.recommendation ? `

## Recommendation
${action.recommendation}` : ''
  return `${generatedBanner}
# Next Product Action

**${action.title}**

## Why now
${action.whyNow}${unlocks}${recommendation}

## Expected outcome
${action.expectedOutcome}
`
}

export function renderMap(snapshot: ProductFrontierSnapshot): string {
  const order = moduleTopologicalOrder(snapshot)
  return `${generatedBanner}
# ${snapshot.product.title}

> ${snapshot.product.initialIdea}

Revision: ${snapshot.revision}

## Product modules

${order.map(id => {
    const module = snapshot.modules.find(value => value.id === id)!
    const realization = snapshot.realizations.find(value => value.moduleId === id && value.status === 'closed')
    return `- **${module.title}** (\`${module.id}\`) — definition: ${module.definitionStatus}; realization: ${realization ? 'closed' : 'not closed'}`
  }).join('\n') || '- No modules yet'}
`
}

export function renderDag(snapshot: ProductFrontierSnapshot): string {
  const ids = new Map([...snapshot.modules].sort((a, b) => a.id.localeCompare(b.id)).map((module, index) => [module.id, `m${index + 1}`]))
  const lines = [generatedBanner, 'flowchart LR']
  for (const module of [...snapshot.modules].sort((a, b) => a.id.localeCompare(b.id))) lines.push(`  ${ids.get(module.id)}["${escapeMermaid(module.title)}\n${module.definitionStatus}"]`)
  for (const module of [...snapshot.modules].sort((a, b) => a.id.localeCompare(b.id))) for (const dependency of [...module.dependencies].sort()) lines.push(`  ${ids.get(dependency)} --> ${ids.get(module.id)}`)
  return `${lines.join('\n')}
`
}

export function renderHandoff(snapshot: ProductFrontierSnapshot, handoff: Handoff): string {
  const module = snapshot.modules.find(value => value.id === handoff.moduleId)!
  const decisions = handoff.decisionIds.map(id => snapshot.decisions.find(value => value.id === id)!).filter(Boolean)
  return `${generatedBanner}
# Handoff: ${module.title}

- Handoff: \`${handoff.id}\` revision ${handoff.revision}
- Product revision: ${handoff.productRevision}
- Status: ${handoff.status}
- Contract digest: \`${handoff.contractDigest}\`

## Product objective
${module.contract.objective}

## Frozen behavior
${lineList(module.contract.frozenBehavior)}

## Governing decisions
${decisions.length ? decisions.map(renderDecision).join('\n') : '- None'}

## Scope
${lineList(module.contract.scope)}

## Non-goals
${lineList(module.contract.nonGoals)}

## Observable acceptance
${module.contract.acceptance.map(value => `- **${value.id}:** ${value.text}`).join('\n')}

## Delivery boundary
Implementation choices remain with Delivery unless they change the frozen behavior above. Closure must reference this exact handoff revision and provide evidence for every acceptance criterion.
`
}

export function renderClosure(snapshot: ProductFrontierSnapshot, closure: Closure): string {
  const realization = snapshot.realizations.find(value => value.id === closure.realizationId)!
  const module = snapshot.modules.find(value => value.id === realization.moduleId)!
  return `${generatedBanner}
# Closure: ${module.title}

- Closure: \`${closure.id}\`
- Handoff: \`${closure.handoffId}\` revision ${closure.handoffRevision}
- Status: ${closure.status}
- Verifier: ${closure.verifier ?? 'Pending'}

## Delivered behavior
${lineList(closure.deliveredBehavior)}

## Acceptance evidence
${closure.acceptanceEvidence.map(value => `- **${value.acceptanceId}: ${value.result}** — ${value.evidence.join('; ') || 'No evidence'}`).join('\n')}

## Checks
${closure.checks.map(value => `- ${value.result}: ${value.command ?? value.system ?? 'unnamed check'}${value.evidenceRef ? ` — ${value.evidenceRef}` : ''}`).join('\n') || '- None'}

## Deviations
${closure.deviations.length ? closure.deviations.map(value => `- ${value.description} — ${value.consequence}${value.requiresProductDecision ? ' (requires Product decision)' : ''}`).join('\n') : '- None'}

## Residual risks
${lineList(closure.residualRisks)}
`
}

export async function generateArtifacts(snapshot: ProductFrontierSnapshot, root = process.cwd()): Promise<string[]> {
  const output = join(workspaceDir(root), 'generated')
  const handoffs = join(output, 'HANDOFFS')
  const closures = join(output, 'CLOSURES')
  await mkdir(handoffs, { recursive: true })
  await mkdir(closures, { recursive: true })
  const files: Array<[string, string]> = [
    [join(output, 'NEXT.md'), renderNext(nextAction(snapshot))],
    [join(output, 'NEXT.json'), `${JSON.stringify(nextAction(snapshot), null, 2)}
`],
    [join(output, 'PRODUCT_MAP.md'), renderMap(snapshot)],
    [join(output, 'PRODUCT_DAG.mmd'), renderDag(snapshot)],
    ...snapshot.handoffs.map(value => [join(handoffs, `${safe(value.id)}.md`), renderHandoff(snapshot, value)] as [string, string]),
    ...snapshot.closures.map(value => [join(closures, `${safe(value.id)}.md`), renderClosure(snapshot, value)] as [string, string]),
  ]
  for (const [path, content] of files) await writeFile(path, content, 'utf8')
  return files.map(([path]) => path)
}

function renderDecision(value: Decision): string { return `- **${value.question}** — ${value.ownerChoice ?? value.status}${value.rationale ? ` (${value.rationale})` : ''}` }
function escapeMermaid(value: string): string { return value.replaceAll('"', "'").replaceAll('\n', ' ') }
function safe(value: string): string { return value.replaceAll(':', '_').replaceAll('/', '_') }
